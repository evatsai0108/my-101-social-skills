// 全域注音開關（預設為開啟，特教學生閱讀鷹架支援）
let isZhuyinEnabled = localStorage.getItem("classroom_zhuyin") !== "false";

// 切換注音開關
function toggleZhuyin() {
  isZhuyinEnabled = !isZhuyinEnabled;
  localStorage.setItem("classroom_zhuyin", isZhuyinEnabled);
  updateZhuyinButton();
  renderSlide();
}

// 更新頂部注音開關按鈕外觀
function updateZhuyinButton() {
  const btn = document.getElementById("zhuyinToggleBtn");
  if (!btn) return;
  if (isZhuyinEnabled) {
    btn.innerHTML = "ㄅ 字嗨注音：開啟";
    btn.classList.add("c-btn-accent");
    btn.title = "點擊切換為純國字無注音模式";
  } else {
    btn.innerHTML = "ㄅ 字嗨注音：關閉";
    btn.classList.remove("c-btn-accent");
    btn.title = "點擊開啟字嗨注音輔助閱讀";
  }
}

// 將文字轉換為「字嗨注音 (Bpmf Zihi Kai Std)」格式（國字右側直排教育部標準注音）
function toZhuyinHtml(text) {
  if (!text) return "";
  const formatted = text.replace(/\n/g, "<br>");
  if (!isZhuyinEnabled) {
    return `<span class="plain-text-mode">${formatted}</span>`;
  }
  return `<span class="zhuyin-mode">${formatted}</span>`;
}
